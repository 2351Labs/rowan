import { CRITERIA, scoreChart } from "../test/chart-a11y/score.mjs";
import { MANUAL_CHECKS } from "../test/chart-a11y/manual.mjs";

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function cell(value) {
  return escapeHtml(value).replace(/\n/g, "<br>");
}

function statusMark(status) {
  if (status === "Supports") return "Supports";
  if (status === "Partially supports") return "Partially supports";
  return "Does not support";
}

function keyboardRows(chart, probe) {
  const keyboard = probe?.keyboard || {};
  const rows = [];
  if (keyboard.tab) {
    rows.push([
      "Tab",
      keyboard.tab.inside
        ? `Landed inside the chart on ${keyboard.tab.target}.`
        : `Did not land inside the chart (${keyboard.tab.target}).`,
    ]);
  } else {
    rows.push([
      "Tab",
      "Not measured in this run. focus() reachability is recorded on the other rows.",
    ]);
  }
  if (chart.keyboard === "points") {
    rows.push([
      "Arrow Right",
      keyboard.arrowMoves
        ? "Moved focus to another point button."
        : "Did not move focus to another point button.",
    ]);
    rows.push(["Home", `Active point key after Home: ${keyboard.homeKey || "none"}.`]);
    rows.push(["End", `Active point key after End: ${keyboard.endKey || "none"}.`]);
    rows.push(["Enter", keyboard.enterActivates ? "Fired rowan-point-activate." : "Did not fire rowan-point-activate."]);
    rows.push(["Space", keyboard.spaceActivates ? "Fired rowan-point-activate." : "Did not fire rowan-point-activate."]);
  } else {
    rows.push([
      "Arrow Right",
      chart.expectArrow
        ? keyboard.arrowAnnounces
          ? `Live region changed to "${keyboard.liveAfter}".`
          : "Live region did not change."
        : "One announced value, so Arrow stays on that value.",
    ]);
    rows.push([
      "Enter and Space",
      keyboard.enterActivates && keyboard.spaceActivates
        ? "Both fired rowan-point-activate."
        : `Enter ${keyboard.enterActivates ? "fired" : "did not fire"} rowan-point-activate. Space ${keyboard.spaceActivates ? "fired" : "did not fire"} it.`,
    ]);
  }
  if (keyboard.legendButtons) {
    rows.push([
      "Legend",
      `${keyboard.legendButtons} toggle button(s) after the lazy legend module loaded. aria-pressed: ${keyboard.legendPressed.join(", ") || "not set"}.`,
    ]);
  }
  return rows;
}

function evidenceRows(chart) {
  return Object.entries(chart.states).map(([name, probe]) => {
    const marks = (probe.contrast?.marks || []).filter((mark) => Number.isFinite(mark.ratio));
    const texts = (probe.contrast?.texts || []).filter((sample) => Number.isFinite(sample.ratio));
    const lowestMark = marks.reduce((best, mark) => (!best || mark.ratio < best.ratio ? mark : best), null);
    const lowestText = texts.reduce((best, sample) => (!best || sample.ratio < best.ratio ? sample : best), null);
    return [
      name,
      probe.axe?.violations?.length
        ? probe.axe.violations.map((violation) => violation.id).join(", ")
        : "none",
      probe.table?.missing?.length ? probe.table.missing.join(", ") : "none",
      probe.keyboard?.focus?.visible ? "visible" : "not visible",
      lowestMark ? `${lowestMark.ratio}:1` : "n/a",
      lowestText ? `${lowestText.ratio}:1` : "n/a",
    ];
  });
}

function knownIssues(scoredCharts, rawCharts) {
  const issues = [];
  for (const scored of scoredCharts) {
    for (const criterion of scored.criteria) {
      if (criterion.status === "Supports") continue;
      issues.push(`**${scored.tag} ${criterion.id} ${criterion.name}:** ${criterion.status}. ${criterion.remarks}`);
    }
    if (scored.unmappedAxe?.length) {
      issues.push(`**${scored.tag} axe:** ${scored.unmappedAxe.join(", ")} did not map onto the criteria table.`);
    }
  }
  for (const chart of rawCharts) {
    const hidden = chart.states["hidden-series"]?.hidden;
    if (hidden && hidden.hiddenMarks === 0) {
      issues.push(
        `**${chart.tag} hidden-series:** setting hidden-series to "${hidden.id}" left the attribute "${hidden.attribute}" and hid 0 marks. The data table still contained the fixture text. This audit did not treat that as a WCAG failure.`,
      );
    }
  }
  return issues;
}

export function renderMarkdown(rawCharts) {
  const scored = rawCharts.map((chart) => scoreChart(chart));
  const issues = knownIssues(scored, rawCharts);
  const lines = [
    "# Chart accessibility conformance",
    "",
    "Conformance report for Rowan chart components against WCAG 2.2 A and AA criteria that this audit measured. This is a self-assessment. It is not a third-party VPAT and it is not an assistive-technology test.",
    "",
    "The pass/fail figures are generated by `scripts/audit-chart-a11y.mjs` from `test/chart-a11y/`. `node scripts/audit-chart-a11y.mjs --check` fails when this file, `docs/chart-accessibility.evidence.json`, or the documentation page drift from a fresh Chromium run.",
    "",
    "## How to read it",
    "",
    "- **Supports** means every measured check for that criterion passed on the audit fixture.",
    "- **Partially supports** means a measured gap remains and the remark cites the measurement, including any text alternative the audit found.",
    "- **Does not support** means a measured check failed and the audit did not find a mitigating text alternative.",
    "- Criteria that are not in the table were not evaluated.",
    "- No NVDA, JAWS, VoiceOver, or TalkBack session was run.",
    "",
    "Each chart is mounted with one fixed fixture. The fixture values are the needles the table check requires. States are default, interactive (or the chart's built-in keyboard mode when it has no `interactive` attribute), hidden-series, forced-colors plus prefers-contrast more, and the dark theme (`data-theme=\"dark\"` with `src/tokens/themes/dark.css`). Axe runs with tags wcag2a, wcag2aa, wcag21a, wcag21aa, and wcag22aa.",
    "",
    "Graphical contrast is the mark's computed fill or stroke, composited with its opacity, against the nearest opaque background. The threshold is 3:1. Text contrast uses 4.5:1 for text under 24px that is not bold, and 3:1 for large text. Focus indicators are measured after `focus({ focusVisible: true })`.",
    "",
    "## Summary",
    "",
    `| Chart | ${CRITERIA.map((criterion) => criterion.id).join(" | ")} | Axe |`,
    `| --- | ${CRITERIA.map(() => "---").join(" | ")} | --- |`,
  ];
  for (const chart of scored) {
    const axe = chart.axe.length ? chart.axe.join(", ") : "none";
    lines.push(
      `| ${chart.tag} | ${chart.criteria.map((criterion) => statusMark(criterion.status)).join(" | ")} | ${axe} |`,
    );
  }
  lines.push("", "## Manual checks", "");
  if (!MANUAL_CHECKS.length) {
    lines.push("No manual check is recorded. Screen-reader behavior is not claimed from an assistive-technology session.");
  } else {
    lines.push("| Check | What was checked | Result |");
    lines.push("| --- | --- | --- |");
    for (const check of MANUAL_CHECKS) {
      lines.push(`| ${check.id} | ${check.checked} | ${check.result} |`);
    }
  }
  lines.push("", "## Known issues", "");
  if (!issues.length) lines.push("The scored criteria all support the measured checks.");
  else lines.push(...issues.map((issue) => `- ${issue}`));

  for (const chart of scored) {
    const raw = rawCharts.find((item) => item.id === chart.id);
    lines.push("", `## ${chart.tag}`, "", chart.title, "", "### WCAG 2.2", "");
    lines.push("| Criterion | Level | Conformance | Remarks |");
    lines.push("| --- | --- | --- | --- |");
    for (const criterion of chart.criteria) {
      lines.push(
        `| ${criterion.id} ${criterion.name} | ${criterion.level} | ${criterion.status} | ${criterion.remarks.replace(/\|/g, "\\|")} |`,
      );
    }
    lines.push("", "### Keyboard", "");
    lines.push("| Key | Measured result |");
    lines.push("| --- | --- |");
    const keySource = raw.states[raw.keyboard === "points" ? "interactive" : "default"];
    for (const [key, result] of keyboardRows(raw, keySource)) {
      lines.push(`| ${key} | ${result.replace(/\|/g, "\\|")} |`);
    }
    lines.push("", "### Screen reader notes", "");
    for (const note of chart.screenReader) {
      if (note.startsWith("-") || note.includes("\n")) {
        lines.push("", "```", note.trim(), "```", "");
      } else lines.push(note, "");
    }
    lines.push("### State evidence", "");
    lines.push("| State | Axe violations | Table needles missing | Focus | Lowest mark | Lowest text |");
    lines.push("| --- | --- | --- | --- | --- | --- |");
    for (const row of evidenceRows(raw)) lines.push(`| ${row.join(" | ")} |`);
    if (raw.states["hidden-series"]?.hidden) {
      const hidden = raw.states["hidden-series"].hidden;
      lines.push(
        "",
        `Hidden-series "${hidden.id}" set the attribute to "${hidden.attribute}" and marked ${hidden.hiddenMarks} plot marks hidden.`,
      );
    }
  }
  lines.push("");
  return `${lines.join("\n")}`;
}

function htmlTable(headers, rows) {
  const head = headers.map((header) => `<th scope="col">${cell(header)}</th>`).join("");
  const body = rows
    .map(
      (row) =>
        `<tr>${row.map((value, index) => (index === 0 ? `<th scope="row">${cell(value)}</th>` : `<td>${cell(value)}</td>`)).join("")}</tr>`,
    )
    .join("");
  return `<div class="docs-compatibility-table-wrap"><table class="docs-compatibility-table"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table></div>`;
}

export function renderPageModule(rawCharts) {
  const scored = rawCharts.map((chart) => scoreChart(chart));
  const issues = knownIssues(scored, rawCharts);
  const summary = htmlTable(
    ["Chart", ...CRITERIA.map((criterion) => criterion.id), "Axe"],
    scored.map((chart) => [
      chart.tag,
      ...chart.criteria.map((criterion) => criterion.status),
      chart.axe.length ? chart.axe.join(", ") : "none",
    ]),
  );
  const manual = MANUAL_CHECKS.length
    ? htmlTable(
        ["Check", "What was checked", "Result"],
        MANUAL_CHECKS.map((check) => [check.id, check.checked, check.result]),
      )
    : "<p>No manual check is recorded. Screen-reader behavior is not claimed from an assistive-technology session.</p>";
  const issueHtml = issues.length
    ? `<ul>${issues.map((issue) => `<li>${cell(issue).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")}</li>`).join("")}</ul>`
    : "<p>The scored criteria all support the measured checks.</p>";
  const sections = scored
    .map((chart) => {
      const raw = rawCharts.find((item) => item.id === chart.id);
      const keySource = raw.states[raw.keyboard === "points" ? "interactive" : "default"];
      const notes = chart.screenReader
        .map((note) =>
          note.includes("\n") || note.includes("accessibility tree")
            ? `<pre class="code-block"><code>${cell(note)}</code></pre>`
            : `<p>${cell(note)}</p>`,
        )
        .join("");
      return `
        <section class="doc-section" data-doc-section id="${chart.id}">
          <h2>${cell(chart.tag)}</h2>
          <p>${cell(chart.title)}</p>
          <h3>WCAG 2.2</h3>
          ${htmlTable(
            ["Criterion", "Level", "Conformance", "Remarks"],
            chart.criteria.map((criterion) => [
              `${criterion.id} ${criterion.name}`,
              criterion.level,
              criterion.status,
              criterion.remarks,
            ]),
          )}
          <h3>Keyboard</h3>
          ${htmlTable(["Key", "Measured result"], keyboardRows(raw, keySource))}
          <h3>Screen reader notes</h3>
          ${notes}
          <h3>State evidence</h3>
          ${htmlTable(
            ["State", "Axe violations", "Table needles missing", "Focus", "Lowest mark", "Lowest text"],
            evidenceRows(raw),
          )}
        </section>`;
    })
    .join("");
  const html = `
    <section class="doc-section" data-doc-section id="chart-a11y-how">
      <h2>How to read this</h2>
      <p>This is a self-assessment of Rowan chart components against the WCAG 2.2 A and AA criteria listed below. It is not a third-party VPAT and it is not an assistive-technology test. The same text is in <code>docs/CHART_ACCESSIBILITY.md</code>.</p>
      <p><strong>Supports</strong> means every measured check for that criterion passed on the audit fixture. <strong>Partially supports</strong> means a measured gap remains and the remark cites the measurement. <strong>Does not support</strong> means a measured check failed without a mitigating text alternative in the audit. Criteria that are not listed were not evaluated.</p>
      <p>Each chart is mounted once per state: default, interactive, hidden-series, forced-colors (with prefers-contrast: more), and the dark theme. Axe uses the wcag2a, wcag2aa, wcag21a, wcag21aa, and wcag22aa tags. Graphical contrast is computed at 3:1 against the chart background. Text uses 4.5:1, or 3:1 for large text. The CI check <code>node scripts/audit-chart-a11y.mjs --check</code> regenerates this page and fails if it has drifted.</p>
    </section>
    <section class="doc-section" data-doc-section id="chart-a11y-summary">
      <h2>Summary</h2>
      ${summary}
    </section>
    <section class="doc-section" data-doc-section id="chart-a11y-manual">
      <h2>Manual checks</h2>
      ${manual}
    </section>
    <section class="doc-section" data-doc-section id="chart-a11y-issues">
      <h2>Known issues</h2>
      ${issueHtml}
    </section>
    ${sections}`;
  return `// Generated by scripts/audit-chart-a11y.mjs. Do not edit by hand.
export const CHART_ACCESSIBILITY_PAGE = {
  id: "chart-accessibility",
  group: "Quality",
  title: "Chart accessibility",
  summary:
    "WCAG 2.2 A and AA conformance for every Rowan chart, scored from the chart accessibility audit.",
  tags: ["accessibility", "charts", "wcag", "vpat"],
  keywords: ["vpat", "wcag", "axe", "keyboard", "screen reader", "contrast", "forced colors"],
  content: () => ${JSON.stringify(html)},
};
`;
}

export function renderEvidence(rawCharts) {
  return `${JSON.stringify({ audit: "test/chart-a11y", states: ["default", "interactive", "hidden-series", "forced-colors", "dark"], charts: rawCharts }, null, 2)}\n`;
}
